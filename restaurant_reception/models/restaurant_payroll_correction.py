from odoo import Command, api, fields, models
from odoo.exceptions import AccessError, UserError, ValidationError

from .restaurant_attendance_entry import LEGACY_LEAVE_STATUSES, OPERATIONAL_STATUSES


ACCOUNTANT_GROUP = 'restaurant_core.group_restaurant_accountant'


class RestaurantPayrollCorrection(models.Model):
    _name = 'restaurant.payroll.correction'
    _description = 'Restaurant Payroll Attendance Correction'
    _inherit = ['mail.thread', 'mail.activity.mixin']
    _order = 'correction_date desc, id desc'
    _mail_post_access = 'read'

    reference = fields.Char(
        required=True, default='New', readonly=True, copy=False, index=True,
    )
    attendance_entry_id = fields.Many2one(
        'restaurant.attendance.entry', required=True, readonly=True,
        ondelete='restrict', index=True, tracking=True,
    )
    attendance_month_id = fields.Many2one(
        'restaurant.attendance.month', required=True, readonly=True,
        ondelete='restrict', index=True, tracking=True,
    )
    source_payroll_batch_id = fields.Many2one(
        'restaurant.payroll.input.batch', required=True, readonly=True,
        ondelete='restrict', index=True, tracking=True,
    )
    source_payroll_line_id = fields.Many2one(
        'restaurant.payroll.input.line', required=True, readonly=True,
        ondelete='restrict', index=True,
    )
    target_payroll_batch_id = fields.Many2one(
        'restaurant.payroll.input.batch', readonly=True, copy=False,
        ondelete='restrict', index=True, tracking=True,
    )
    target_payroll_line_id = fields.Many2one(
        'restaurant.payroll.input.line', readonly=True, copy=False,
        ondelete='restrict', index=True,
    )
    employee_id = fields.Many2one(
        'hr.employee', required=True, readonly=True, ondelete='restrict',
        index=True, tracking=True,
    )
    company_id = fields.Many2one(
        'res.company', required=True, readonly=True, ondelete='restrict',
        index=True,
    )
    branch_id = fields.Many2one(
        'restaurant.branch', required=True, readonly=True, ondelete='restrict',
        index=True, tracking=True,
    )
    currency_id = fields.Many2one(
        related='company_id.currency_id', readonly=True,
    )
    correction_date = fields.Date(required=True, readonly=True, index=True)
    original_status = fields.Selection(
        OPERATIONAL_STATUSES + LEGACY_LEAVE_STATUSES,
        required=True, readonly=True,
    )
    corrected_status = fields.Selection(
        OPERATIONAL_STATUSES + LEGACY_LEAVE_STATUSES,
        required=True, readonly=True,
    )
    daily_rate = fields.Monetary(
        currency_field='currency_id', required=True, readonly=True,
    )
    amount_signed = fields.Monetary(
        currency_field='currency_id', required=True, readonly=True,
        help='Positive means money owed to the employee; negative means a deduction.',
    )
    allowance_amount = fields.Monetary(
        currency_field='currency_id', required=True, readonly=True,
    )
    deduction_amount = fields.Monetary(
        currency_field='currency_id', required=True, readonly=True,
    )
    correction_note = fields.Text(required=True, readonly=True, tracking=True)
    settlement_method = fields.Selection([
        ('next_payroll', 'Carry to Next Payroll'),
        ('cash_now', 'Pay Now - Cash'),
    ], required=True, readonly=True, tracking=True, index=True)
    state = fields.Selection([
        ('pending_carry', 'Pending Next Payroll'),
        ('awaiting_cash', 'Awaiting Cash Settlement'),
        ('carried', 'Added to Next Payroll'),
        ('cash_settled', 'Cash Settled'),
        ('cancelled', 'Cancelled'),
    ], required=True, readonly=True, tracking=True, index=True)
    cash_settlement_date = fields.Date(copy=False, tracking=True)
    cash_settlement_note = fields.Text(copy=False, tracking=True)
    cash_receipt = fields.Binary(attachment=True, copy=False)
    cash_receipt_filename = fields.Char(copy=False)
    cash_settled_by = fields.Many2one(
        'res.users', readonly=True, copy=False, tracking=True,
    )
    cash_settled_at = fields.Datetime(readonly=True, copy=False, tracking=True)

    @api.model_create_multi
    def create(self, vals_list):
        if not (self.env.su and self.env.context.get('restaurant_payroll_correction_internal')):
            raise AccessError(self.env._(
                'Payroll correction records are generated by audited attendance corrections.'
            ))
        sequence = self.env['ir.sequence'].sudo().search([
            ('code', '=', 'restaurant.payroll.correction'),
            ('company_id', '=', False),
        ], limit=1)
        if not sequence:
            raise UserError(self.env._('The payroll correction sequence is not configured.'))
        prepared = []
        for vals in vals_list:
            values = dict(vals)
            if not values.get('reference') or values.get('reference') in ('New', '/'):
                values['reference'] = sequence.next_by_id()
            prepared.append(values)
        return super().create(prepared)

    def write(self, vals):
        if self.env.context.get('restaurant_payroll_correction_internal'):
            return super().write(vals)
        if not (
            self.env.user.has_group(ACCOUNTANT_GROUP)
            or self.env.user.has_group('base.group_system')
        ):
            raise AccessError(self.env._(
                'Only Payroll/Accounting can record a cash correction settlement.'
            ))
        allowed = {
            'cash_settlement_date', 'cash_settlement_note',
            'cash_receipt', 'cash_receipt_filename',
        }
        if set(vals) - allowed:
            raise AccessError(self.env._(
                'Correction amount, source, settlement method, and status are audit locked.'
            ))
        if any(record.state != 'awaiting_cash' for record in self):
            raise AccessError(self.env._(
                'Cash details can be edited only while settlement is awaiting confirmation.'
            ))
        return super().write(vals)

    def unlink(self):
        raise AccessError(self.env._('Audited payroll correction records cannot be deleted.'))

    def action_mark_cash_settled(self):
        self.ensure_one()
        if not (
            self.env.user.has_group(ACCOUNTANT_GROUP)
            or self.env.user.has_group('base.group_system')
        ):
            raise AccessError(self.env._(
                'Only Payroll/Accounting can confirm a cash correction settlement.'
            ))
        if self.state != 'awaiting_cash':
            raise UserError(self.env._('Only an awaiting cash correction can be settled.'))
        if self.amount_signed <= 0:
            raise ValidationError(self.env._(
                'Pay Now - Cash is available only when money is owed to the employee.'
            ))
        if not self.cash_settlement_date:
            raise ValidationError(self.env._('Enter the cash settlement date.'))
        if not (self.cash_settlement_note or '').strip():
            raise ValidationError(self.env._('Enter the cash settlement note.'))
        if not self.cash_receipt:
            raise ValidationError(self.env._(
                'Upload the signed employee receipt or other cash delivery proof.'
            ))
        self.sudo().with_context(restaurant_payroll_correction_internal=True).write({
            'state': 'cash_settled',
            'cash_settled_by': self.env.uid,
            'cash_settled_at': fields.Datetime.now(),
        })
        self.message_post(body=self.env._(
            'Cash payroll correction of %(amount)s confirmed by %(user)s. '
            'This amount will not be carried to a future payroll input.',
            amount=self.allowance_amount,
            user=self.env.user.name,
        ))
        return True

    def _attach_to_existing_draft_payroll(self):
        for correction in self.filtered(lambda item: item.state == 'pending_carry'):
            target = self.env['restaurant.payroll.input.batch'].sudo().search([
                ('company_id', '=', correction.company_id.id),
                ('branch_id', '=', correction.branch_id.id),
                ('month_start', '>', correction.attendance_month_id.month_end),
                ('state', '=', 'draft'),
            ], order='month_start, id', limit=1)
            if target:
                target._apply_pending_payroll_corrections()


class RestaurantAttendanceEntryPayrollCorrection(models.Model):
    _inherit = 'restaurant.attendance.entry'

    payroll_correction_ids = fields.One2many(
        'restaurant.payroll.correction', 'attendance_entry_id',
        string='Payroll Corrections', readonly=True, copy=False,
    )
    payroll_correction_count = fields.Integer(
        compute='_compute_payroll_correction_count',
    )

    @api.depends('payroll_correction_ids')
    def _compute_payroll_correction_count(self):
        for entry in self:
            entry.payroll_correction_count = len(entry.payroll_correction_ids)

    def _automatic_snapshot_for_correction(self, payroll_line):
        self.ensure_one()
        source_entries = self.sudo().search([
            ('id', '!=', self.id),
            ('employee_id', '=', self.employee_id.id),
            ('branch_id', '=', self.branch_id.id),
            ('attendance_date', '>=', payroll_line.batch_id.month_start),
            ('attendance_date', '<=', payroll_line.batch_id.month_end),
            ('state', '=', 'approved'),
        ], order='attendance_date, id') | self
        source_entries = source_entries.sorted(key=lambda entry: (entry.attendance_date, entry.id))
        unexcused_absences = source_entries.filtered(lambda entry: (
            entry.status == 'absent' and not entry.absence_excused
        ))
        unpaid_leaves = source_entries.filtered(lambda entry: (
            entry.status in ('annual_leave', 'sick_leave', 'emergency_leave')
            and entry.leave_payroll_treatment == 'unpaid'
        ))
        overtime = source_entries.filtered(lambda entry: (
            entry.status == 'overtime_day'
            and entry.overtime_measurement == 'approved_day'
            and entry.scheduled_day_off
        ))
        eligible_overtime = overtime[:4]
        offset_count = min(len(unexcused_absences), len(eligible_overtime))
        deductions = unexcused_absences[offset_count:] | unpaid_leaves
        payable_overtime = eligible_overtime[offset_count:]
        daily_rate = payroll_line.daily_rate or (
            payroll_line.base_salary / 30 if payroll_line.base_salary else 0
        )
        return {
            'daily_rate': daily_rate,
            'automatic_absence_deduction': self.company_id.currency_id.round(
                daily_rate * len(deductions)
            ),
            'automatic_overtime_amount': self.company_id.currency_id.round(
                len(payable_overtime) * 100
            ),
            'source_entries': source_entries,
            'deduction_sources': deductions,
            'overtime_sources': overtime,
        }

    def _create_processed_payroll_correction(self):
        self.ensure_one()
        if not self.hr_monthly_correction:
            return False
        month = self._open_monthly_correction()
        if not month:
            raise ValidationError(self.env._(
                'The monthly attendance period must remain open for correction.'
            ))
        batch = self.env['restaurant.payroll.input.batch'].sudo().search([
            ('attendance_month_id', '=', month.id),
        ], limit=1)
        if not batch:
            return False
        line = batch.line_ids.filtered(lambda item: item.employee_id == self.employee_id)[:1]
        if not line:
            raise ValidationError(self.env._(
                'The payroll input has no employee line for %(employee)s.',
                employee=self.employee_id.display_name,
            ))
        snapshot = self._automatic_snapshot_for_correction(line)
        if batch.state == 'draft':
            line.sudo().with_context(restaurant_payroll_internal=True).write({
                'automatic_absence_deduction': snapshot['automatic_absence_deduction'],
                'automatic_overtime_amount': snapshot['automatic_overtime_amount'],
                'source_attendance_ids': [Command.set(snapshot['source_entries'].ids)],
                'unpaid_absence_source_ids': [Command.set(snapshot['deduction_sources'].ids)],
                'overtime_source_ids': [Command.set(snapshot['overtime_sources'].ids)],
            })
            batch.message_post(body=self.env._(
                'Draft payroll inputs refreshed for %(employee)s from audited attendance '
                'correction %(entry)s.',
                employee=self.employee_id.display_name,
                entry=self.display_name,
            ))
            return False
        if batch.state == 'ready':
            raise ValidationError(self.env._(
                'Payroll input %(payroll)s is Ready for Payroll. Return it to HR correction '
                'before applying this attendance change.',
                payroll=batch.reference,
            ))

        new_automatic_net = (
            snapshot['automatic_overtime_amount']
            - snapshot['automatic_absence_deduction']
        )
        processed_automatic_net = (
            line.automatic_overtime_amount - line.automatic_absence_deduction
        )
        desired_total = self.company_id.currency_id.round(
            new_automatic_net - processed_automatic_net
        )
        prior_total = sum(self.env['restaurant.payroll.correction'].sudo().search([
            ('source_payroll_line_id', '=', line.id),
            ('state', '!=', 'cancelled'),
        ]).mapped('amount_signed'))
        difference = self.company_id.currency_id.round(desired_total - prior_total)
        if self.company_id.currency_id.is_zero(difference):
            self.message_post(body=self.env._(
                'The audited attendance correction has no remaining payroll difference.'
            ))
            return False
        note = (self.correction_payroll_note or '').strip()
        if not note:
            raise ValidationError(self.env._(
                'Enter the Payroll Correction Note before applying a correction that '
                'changes processed payroll.'
            ))
        method = self.correction_settlement_method or 'next_payroll'
        if method == 'cash_now' and difference <= 0:
            raise ValidationError(self.env._(
                'Pay Now - Cash can be used only when money is owed to the employee. '
                'Use Carry to Next Payroll for an additional deduction.'
            ))
        correction = self.env['restaurant.payroll.correction'].sudo().with_context(
            restaurant_payroll_correction_internal=True,
        ).create({
            'attendance_entry_id': self.id,
            'attendance_month_id': month.id,
            'source_payroll_batch_id': batch.id,
            'source_payroll_line_id': line.id,
            'employee_id': self.employee_id.id,
            'company_id': self.company_id.id,
            'branch_id': self.branch_id.id,
            'correction_date': self.attendance_date,
            'original_status': self.correction_original_status,
            'corrected_status': self.status,
            'daily_rate': snapshot['daily_rate'],
            'amount_signed': difference,
            'allowance_amount': max(difference, 0),
            'deduction_amount': max(-difference, 0),
            'correction_note': note,
            'settlement_method': method,
            'state': 'awaiting_cash' if method == 'cash_now' else 'pending_carry',
        })
        correction._attach_to_existing_draft_payroll()
        self.message_post(body=self.env._(
            'Payroll correction %(reference)s created for %(amount)s using %(method)s.',
            reference=correction.reference,
            amount=abs(difference),
            method=dict(correction._fields['settlement_method']._description_selection(
                correction.env
            ))[method],
        ))
        return correction


class RestaurantPayrollInputBatchCorrection(models.Model):
    _inherit = 'restaurant.payroll.input.batch'

    def _generate_lines(self):
        result = super()._generate_lines()
        self._apply_pending_payroll_corrections()
        return result

    def _apply_pending_payroll_corrections(self):
        Correction = self.env['restaurant.payroll.correction'].sudo()
        Line = self.env['restaurant.payroll.input.line'].sudo().with_context(
            restaurant_payroll_internal=True,
        )
        for batch in self.filtered(lambda item: item.state == 'draft'):
            corrections = Correction.search([
                ('state', '=', 'pending_carry'),
                ('company_id', '=', batch.company_id.id),
                ('branch_id', '=', batch.branch_id.id),
                ('attendance_month_id.month_end', '<', batch.month_start),
            ], order='correction_date, id')
            if not corrections:
                continue
            for employee in corrections.employee_id:
                employee_corrections = corrections.filtered(
                    lambda item: item.employee_id == employee
                )
                line = batch.line_ids.filtered(
                    lambda item: item.employee_id == employee
                )[:1]
                if not line:
                    base_salary = employee.sudo().wage or 0
                    line = Line.create({
                        'batch_id': batch.id,
                        'employee_id': employee.id,
                        'calculation_version': 'automatic_days',
                        'base_salary': base_salary,
                        'daily_rate': base_salary / 30 if base_salary else 0,
                    })
                allowance = sum(employee_corrections.mapped('allowance_amount'))
                deduction = sum(employee_corrections.mapped('deduction_amount'))
                line.with_context(restaurant_payroll_internal=True).write({
                    'correction_allowance_amount': line.correction_allowance_amount + allowance,
                    'correction_deduction_amount': line.correction_deduction_amount + deduction,
                    'correction_ids': [Command.link(item.id) for item in employee_corrections],
                })
                employee_corrections.with_context(
                    restaurant_payroll_correction_internal=True,
                ).write({
                    'state': 'carried',
                    'target_payroll_batch_id': batch.id,
                    'target_payroll_line_id': line.id,
                })
            batch.message_post(body=self.env._(
                '%s audited attendance payroll correction(s) added automatically.',
                len(corrections),
            ))
        return True

    def unlink(self):
        carried = self.env['restaurant.payroll.correction'].sudo().search([
            ('target_payroll_batch_id', 'in', self.ids),
            ('state', '=', 'carried'),
        ])
        if carried:
            carried.with_context(restaurant_payroll_correction_internal=True).write({
                'state': 'pending_carry',
                'target_payroll_batch_id': False,
                'target_payroll_line_id': False,
            })
        return super().unlink()


class RestaurantPayrollInputLineCorrection(models.Model):
    _inherit = 'restaurant.payroll.input.line'

    correction_allowance_amount = fields.Monetary(
        string='Attendance Correction Allowance', currency_field='currency_id',
        readonly=True,
    )
    correction_deduction_amount = fields.Monetary(
        string='Attendance Correction Deduction', currency_field='currency_id',
        readonly=True,
    )
    correction_ids = fields.Many2many(
        'restaurant.payroll.correction',
        'restaurant_payroll_line_correction_rel',
        'payroll_line_id', 'correction_id',
        string='Attendance Corrections', readonly=True, copy=False,
    )

    @api.depends(
        'base_salary', 'overtime_amount', 'automatic_overtime_amount',
        'allowance_amount', 'deduction_amount', 'automatic_absence_deduction',
        'correction_allowance_amount', 'correction_deduction_amount',
    )
    def _compute_input_total(self):
        for line in self:
            line.input_total = (
                line.base_salary + line.overtime_amount
                + line.automatic_overtime_amount + line.allowance_amount
                + line.correction_allowance_amount
                - line.automatic_absence_deduction - line.deduction_amount
                - line.correction_deduction_amount
            )
